def neg_log_likelihood(args, counts, durations: np.ndarray, thetas):
    n, inten, acc = args
    expected = count_rate(
        n,
        intensity=inten,
        timespans=durations / 3600_000,
        thetas=thetas,
        accidentals=acc,
    )
    return np.sum(-np.asarray(counts) * np.log(expected) + expected)


