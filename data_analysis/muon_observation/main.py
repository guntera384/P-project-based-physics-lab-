def neg_log_likelihood(
    args, counts, durations: np.ndarray, thetas, dist=PLANE_DIST, side=SIDE_LENGTH
):
    n, inten, acc = args
    expected = count_rate(
        n,
        intensity=inten,
        timespans=durations / 3600_000,
        thetas=thetas,
        accidentals=acc,
        distance=dist,
        side_length=side,
    )
    return np.sum(expected - counts + xlogy(counts, counts / expected))


